"""Generate data/sql/seed.sql from the seed JSON, the corpus front matter and the golden sets.

IDs are deterministic UUIDv5 values, so re-running gives the same file and the
same IDs on every machine. Every insert is ON CONFLICT DO NOTHING, so loading the
file twice is safe. Sensor readings, health assessments, re-scores and
audit events are NOT seeded: the replay engine writes them during a run.
Document chunks and Qdrant points are written by POST /admin/ingest.

Usage:
    python build_seed_sql.py DATA_DIR OUT_SQL
"""
from __future__ import annotations

import json
import sys
import uuid
from pathlib import Path

import yaml

NS = uuid.UUID("5afe1009-0000-4000-8000-000000000100")


def uid(kind: str, key: str) -> str:
    return str(uuid.uuid5(NS, f"{kind}:{key}"))


def lit(v) -> str:
    """SQL literal for a Python value."""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, (dict, list)):
        return "'" + json.dumps(v, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def insert(table: str, rows: list[dict]) -> str:
    if not rows:
        return ""
    cols = list(rows[0].keys())
    values = ",\n  ".join("(" + ", ".join(lit(r[c]) for c in cols) + ")" for r in rows)
    return f'INSERT INTO "{table}" ({", ".join(chr(34) + c + chr(34) for c in cols)}) VALUES\n  {values}\nON CONFLICT DO NOTHING;\n\n'


def main(data_dir: str, out_sql: str) -> None:
    root = Path(data_dir)
    am = json.loads((root / "seed/asset_model_unit100.json").read_text())
    hz = json.loads((root / "seed/hazop_unit100.json").read_text())
    rules = json.loads((root / "seed/risk_rule_set_v1.json").read_text())
    users = json.loads((root / "seed/users.json").read_text())["users"]
    prompts = json.loads((root / "seed/prompt_templates.json").read_text())["templates"]
    health = json.loads((root / "seed/health_models.json").read_text())
    mapping = json.loads((root / "replay/tag_mapping.json").read_text())["tags"]

    site_id = uid("site", am["site"]["code"])
    unit_id = uid("unit", am["unit"]["code"])
    node_id = {n["code"]: uid("node", n["code"]) for n in am["nodes"]}
    asset_id = {a["tag"]: uid("asset", a["tag"]) for a in am["assets"]}
    sg_id = {s["ref_code"]: uid("safeguard", s["ref_code"]) for s in am["safeguards"]}
    user_id = {u["handle"]: uid("user", u["handle"]) for u in users}
    hmodel = {m["driver_tag"]: m for m in health["models"]}

    sql = ["-- SafeLoop MVP seed data (generated by tools/build_seed_sql.py). Synthetic plant, public-proxy signals.\n",
           "BEGIN;\n\n"]
    sql.append(insert("sites", [{"id": site_id, "code": am["site"]["code"], "name": am["site"]["name"], "origin": "synthetic"}]))
    sql.append(insert("units", [{"id": unit_id, "site_id": site_id, "code": am["unit"]["code"], "name": am["unit"]["name"]}]))
    sql.append(insert("process_nodes", [{"id": node_id[n["code"]], "unit_id": unit_id, "code": n["code"], "name": n["name"],
                                         "design_intent": n["design_intent"]} for n in am["nodes"]]))
    sql.append(insert("assets", [{"id": asset_id[a["tag"]], "unit_id": unit_id, "node_id": node_id[a["node"]], "tag": a["tag"],
                                  "name": a["name"], "asset_class": a["asset_class"], "criticality": a["criticality"],
                                  "standby_of_id": None, "is_monitored": a["is_monitored"], "origin": "synthetic"}
                                 for a in am["assets"]]))
    for a in am["assets"]:
        if a.get("standby_of"):
            sql.append(f'UPDATE "assets" SET "standby_of_id" = {lit(asset_id[a["standby_of"]])} WHERE "id" = {lit(asset_id[a["tag"]])};\n\n')
    sql.append(insert("asset_links", [{"code": l["code"], "from_asset_id": asset_id[l["from"]], "to_asset_id": asset_id[l["to"]],
                                       "relation": l["relation"]} for l in am["asset_links"]]))
    tags = []
    for t in am["sensor_tags"]:
        transform = {"mapping": mapping[t["tag"]]["transform"]}
        if t["tag"] in hmodel:
            transform["health_models"] = [m for m in health["models"] if m["driver_tag"] == t["tag"]]
        tags.append({"id": uid("tag", t["tag"]), "asset_id": asset_id[t["asset"]], "tag": t["tag"], "description": t["description"],
                     "eng_unit": t["eng_unit"], "alert_low": t.get("alert_low"), "alert_high": t.get("alert_high"),
                     "alert_high_tightened": t.get("alert_high_tightened"), "source_dataset": t["source_dataset"],
                     "source_signal": t["source_signal"][:128], "transform": json.dumps(transform), "origin": t["origin"]})
    sql.append(insert("sensor_tags", tags))
    sql.append(insert("safeguards", [{"id": sg_id[s["ref_code"]], "unit_id": unit_id, "ref_code": s["ref_code"], "type": s["type"],
                                      "description": s["description"], "last_test_date": s["last_test_date"]}
                                     for s in am["safeguards"]]))
    sql.append(insert("safeguard_dependencies", [{"safeguard_id": sg_id[s["ref_code"]], "asset_id": asset_id[a]}
                                                 for s in am["safeguards"] for a in s["depends_on"]]))
    rows, row_sg, recs = [], [], []
    for r in hz["rows"]:
        rid = uid("hazop_row", f'{r["row_code"]}:v1')
        rows.append({"id": rid, "node_id": node_id[r["node"]], "row_code": r["row_code"], "version": 1,
                     "guide_word": r["guide_word"], "parameter": r["parameter"], "deviation": r["deviation"], "cause": r["cause"],
                     "cause_asset_id": asset_id.get(r["cause_asset"]) if r["cause_asset"] else None,
                     "consequence": r["consequence"], "severity": r["severity"], "likelihood_base": r["likelihood_base"],
                     "status": "approved"})
        row_sg += [{"hazop_row_id": rid, "safeguard_id": sg_id[s], "credited": True} for s in r["safeguards"]]
        recs += [{"id": uid("hazop_rec", f'{r["row_code"]}:{i}'), "hazop_row_id": rid, "text": t,
                  "owner_role": "process_safety_engineer"} for i, t in enumerate(r["recommendations"])]
    sql.append(insert("hazop_rows", rows))
    sql.append(insert("hazop_row_safeguards", row_sg))
    sql.append(insert("hazop_recommendations", recs))
    sql.append(insert("risk_rule_sets", [{"id": uid("rule_set", rules["version"]), "version": rules["version"], "rules": rules,
                                          "status": rules["status"], "approved_by": None, "approved_at": None}]))
    sql.append(insert("users", [{"id": user_id[u["handle"]], "handle": u["handle"], "display_name": u["display_name"],
                                 "email": u["email"], "role": u["role"], "is_demo": True} for u in users]))
    sql.append(insert("prompt_templates", [{"id": uid("prompt", p["version"]), "agent": p["agent"], "version": p["version"],
                                            "template": p["template"], "output_schema": p["output_schema"]} for p in prompts]))

    docs, doc_assets = [], []
    for f in sorted((root / "corpus").glob("*.md")):
        fm = yaml.safe_load(f.read_text().split("---")[1])
        did = uid("document", f'{fm["doc_code"]}@{fm["revision"]}')
        docs.append({"id": did, "doc_code": fm["doc_code"], "title": fm["title"], "type": fm["type"], "revision": str(fm["revision"]),
                     "effective_date": str(fm["effective_date"]), "is_current": fm["is_current"], "origin": "synthetic",
                     "generator_model": None, "reviewed_by": user_id["rina"], "storage_uri": f"data/corpus/{f.name}"})
        doc_assets += [{"document_id": did, "asset_id": asset_id[t]} for t in fm["asset_tags"]]
    sql.append(insert("documents", docs))
    sql.append(insert("document_assets", doc_assets))

    golden = []
    sets = {"hazop_rows": "hazop_rows.jsonl", "qa": "qa.jsonl", "out_of_corpus": "out_of_corpus.jsonl",
            "guardrail": "guardrail.jsonl", "rca": "rca_cases.jsonl"}
    expected_keys = {"hazop_rows": None, "qa": ["expected_kind", "expected_docs", "must_include", "must_not_cite"],
                     "out_of_corpus": ["expected_kind", "why_missing"], "guardrail": ["expected", "expected_rule"],
                     "rca": ["true_root_cause", "accept_keywords", "contributing", "evidence"]}
    for set_name, fname in sets.items():
        for line in (root / "golden" / fname).read_text().splitlines():
            if not line.strip():
                continue
            item = json.loads(line)
            ek = expected_keys[set_name]
            if ek is None:  # hazop golden rows: the whole scenario is the expected answer
                inp = {"target_row": item["target_row"]}
                exp = {k: v for k, v in item.items() if k not in ("id", "split", "target_row")}
            else:
                exp = {k: item[k] for k in ek}
                inp = {k: v for k, v in item.items() if k not in ek and k not in ("id", "split")}
            golden.append({"id": uid("golden", item["id"]), "item_code": item["id"], "set_name": set_name, "split": item["split"],
                           "input": inp, "expected": exp, "authored_by": user_id["rina"], "reviewed_by": user_id["dimas"]})
    sql.append(insert("golden_items", golden))
    sql.append("COMMIT;\n")
    Path(out_sql).parent.mkdir(parents=True, exist_ok=True)
    Path(out_sql).write_text("".join(sql))
    print(f"wrote {out_sql}: {len(am['assets'])} assets, {len(tags)} tags, {len(rows)} HAZOP rows, "
          f"{len(docs)} documents, {len(golden)} golden items")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
